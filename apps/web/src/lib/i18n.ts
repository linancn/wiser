export function switchLocalePath(pathname: string, locale: Locale): string {
  const segments = pathname.split('/');
  if (segments.length > 1 && isLocale(segments[1] ?? '')) {
    segments[1] = locale;
    return segments.join('/') || `/${locale}/scenarios`;
  }
  return `/${locale}/scenarios`;
}
